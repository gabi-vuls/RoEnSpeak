"""Windows version resource for the RoEnSpeak executables, derived from app.contracts.APP_VERSION.

APP_VERSION in app/contracts.py is the single source of truth. This module reads it with a regex
(no import of the app package, so it works from any interpreter) and is used by:

  * build/roenspeak.spec   -> version_info(exe_name, description) builds the VSVersionInfo object
                              embedded into RoEnSpeak.exe and RoEnSpeak-cli.exe;
  * build/build.ps1        -> `python build/gen_version_info.py --version` passes the version to ISCC;
  * humans                 -> `python build/gen_version_info.py --text [OUT]` writes the resource in
                              PyInstaller's text format (default: build/work/version_info.txt) for review.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACTS = ROOT / "app" / "contracts.py"

COMPANY = "RoEnSpeak"
PRODUCT = "RoEnSpeak"
COPYRIGHT = "RoEnSpeak contributors"


def app_name() -> str:
    m = re.search(r'^APP_NAME\s*=\s*"([^"]+)"', CONTRACTS.read_text(encoding="utf-8"), re.M)
    if not m:
        raise SystemExit(f"APP_NAME not found in {CONTRACTS}")
    return m.group(1)


def app_version() -> str:
    m = re.search(r'^APP_VERSION\s*=\s*"([^"]+)"', CONTRACTS.read_text(encoding="utf-8"), re.M)
    if not m:
        raise SystemExit(f"APP_VERSION not found in {CONTRACTS}")
    return m.group(1)


def version_tuple(version: str | None = None) -> tuple[int, int, int, int]:
    """"0.1.0" -> (0, 1, 0, 0); pre-release suffixes ("1.2.0rc1") keep only their leading digits."""
    parts = []
    for p in (version or app_version()).split(".")[:4]:
        m = re.match(r"\d+", p)
        parts.append(int(m.group(0)) if m else 0)
    while len(parts) < 4:
        parts.append(0)
    return tuple(parts)  # type: ignore[return-value]


def _strings(exe_name: str, description: str) -> list[tuple[str, str]]:
    version = app_version()
    return [
        ("CompanyName", COMPANY),
        ("FileDescription", description),
        ("FileVersion", version),
        ("InternalName", Path(exe_name).stem),
        ("LegalCopyright", COPYRIGHT),
        ("OriginalFilename", exe_name),
        ("ProductName", PRODUCT),
        ("ProductVersion", version),
    ]


def version_info(exe_name: str, description: str):
    """VSVersionInfo object for PyInstaller's EXE(version=...). Only importable under PyInstaller."""
    from PyInstaller.utils.win32.versioninfo import (
        FixedFileInfo,
        StringFileInfo,
        StringStruct,
        StringTable,
        VarFileInfo,
        VarStruct,
        VSVersionInfo,
    )

    vt = version_tuple()
    return VSVersionInfo(
        ffi=FixedFileInfo(filevers=vt, prodvers=vt, mask=0x3F, flags=0x0, OS=0x40004, fileType=0x1,
                          subtype=0x0, date=(0, 0)),
        kids=[
            StringFileInfo([StringTable("040904B0", [StringStruct(k, v) for k, v in _strings(exe_name, description)])]),
            VarFileInfo([VarStruct("Translation", [0x0409, 1200])]),
        ],
    )


def version_text(exe_name: str = "RoEnSpeak.exe", description: str = "RoEnSpeak: speak Romanian, type English") -> str:
    """The same resource in PyInstaller's text format (what `pyi-grab_version` prints)."""
    vt = version_tuple()
    strings = ",\n".join(f"          StringStruct('{k}', '{v}')" for k, v in _strings(exe_name, description))
    return f"""# UTF-8
# Generated by build/gen_version_info.py from app/contracts.py APP_VERSION. Do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={vt},
    prodvers={vt},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [
{strings}
        ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--version", action="store_true", help="print APP_VERSION")
    g.add_argument("--name", action="store_true", help="print APP_NAME")
    g.add_argument("--text", nargs="?", const=str(ROOT / "build" / "work" / "version_info.txt"), metavar="OUT",
                   help="write the version resource in PyInstaller text format")
    args = p.parse_args(argv)
    if args.version:
        print(app_version())
    elif args.name:
        print(app_name())
    else:
        out = Path(args.text)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(version_text(), encoding="utf-8")
        print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
